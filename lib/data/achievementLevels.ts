const STANDARD_CODE_PATTERN = /9수\d{2}-\d{2}/;

/** 자유 텍스트(예: "[9수01-06] 순환소수의 뜻을...")에서 성취기준 코드를 추출한다. */
export function extractStandardCode(text?: string | null): string | null {
  if (!text) return null;
  const match = text.match(STANDARD_CODE_PATTERN);
  return match ? match[0] : null;
}

/** 성취기준 코드로 A~E 성취수준 묶음을 조회한다. */
export function getAchievementLevels(code?: string | null): LevelSet | null {
  if (!code) return null;
  return achievementLevels[code] || null;
}

/**
 * 성취기준에 연결된 A~E 성취수준 전체를 프롬프트용 문자열로 변환한다.
 * 모델이 난이도(상~하)를 보정하는 데 사용한다.
 */
export function formatLevelSpectrum(code?: string | null): string {
  const levels = getAchievementLevels(code);
  if (!levels) return "";
  return [
    "[성취기준별 성취수준 명세 (난이도 보정 기준, A 상위 ~ E 하위)]",
    `- 수준 A: ${levels.A}`,
    `- 수준 B: ${levels.B}`,
    `- 수준 C: ${levels.C}`,
    `- 수준 D: ${levels.D}`,
    `- 수준 E: ${levels.E}`
  ].join("\n");
}

/** 특정 목표 수준의 수행 특성만 추출(수준별 문항 생성용). */
